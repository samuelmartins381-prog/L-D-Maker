import { cpSync, existsSync, mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import type { LlmAnswer, LlmCall, LlmClient } from "./llm.ts";
import {
  estimateStoryboard,
  GENERATION_LOG,
  GenerationError,
  generateStoryboard,
} from "./storyboard.ts";

const DEMO = new URL(
  "../../../../projects/mouvement-mecanique",
  import.meta.url,
).pathname;

/** A copy of the demo project with its sources read, without its storyboard. */
function demo(): string {
  const dir = mkdtempSync(join(tmpdir(), "ldm-engine-"));
  for (const f of ["project.yaml", "sources", "ingest"])
    cpSync(join(DEMO, f), join(dir, f), { recursive: true });
  return dir;
}

/** The hand-written demo storyboard, as Claude would answer it (no schemaVersion, no module). */
function handDraft(): Record<string, unknown> {
  const {
    schemaVersion: _v,
    module: _m,
    ...draft
  } = parse(readFileSync(join(DEMO, "storyboard.yaml"), "utf8"));
  return draft;
}

/** Replays answers in order and records the calls. */
function fake(answers: string[]): LlmClient & { calls: LlmCall[] } {
  const calls: LlmCall[] = [];
  return {
    calls,
    async countTokens() {
      return 20_000;
    },
    async complete(call, onProgress) {
      calls.push(structuredClone(call));
      const text = answers.shift() ?? "{}";
      onProgress?.(text.length);
      const answer: LlmAnswer = {
        text,
        content: [{ type: "text", text }],
        stopReason: "end_turn",
        usage: {
          input_tokens: 1_000,
          output_tokens: 10_000,
          cache_read_input_tokens: 19_000,
        },
      };
      return answer;
    },
  };
}

describe("generateStoryboard", () => {
  it("sends the sources once, returns the problems for correction and writes the best storyboard", async () => {
    const dir = demo();
    const broken = handDraft();
    const [firstObjective] = broken.objectives as { sourceRefs: string[] }[];
    if (firstObjective)
      firstObjective.sourceRefs = ["guide-mouvement.pdf#h-invented"];
    const client = fake([JSON.stringify(broken), JSON.stringify(handDraft())]);
    const stages: string[] = [];

    const r = await generateStoryboard(dir, {
      client,
      onProgress: (e) => stages.push(e.stage),
    });

    expect(r.rounds).toBe(2);
    expect(r.issues).toEqual([]);
    expect(r.storyboard.module.id).toBe("mouvement-mecanique");
    expect(r.usage.output_tokens).toBe(20_000);
    expect(r.costUsd).toBeCloseTo(
      (2 * 1_000 * 4 + 2 * 19_000 * 0.2 + 20_000 * 20) / 1e6,
    );
    expect(stages).toEqual([
      "writing",
      "checking",
      "writing",
      "checking",
      "done",
    ]);

    // First call: sources, images, anchor list (cached), then the project choices.
    const first = client.calls[0]?.messages[0]?.content as {
      type: string;
      text?: string;
      cache_control?: unknown;
    }[];
    expect(first.some((b) => b.type === "image")).toBe(true);
    expect(first.find((b) => b.cache_control)?.text).toMatch(
      /guide-mouvement\.pdf#p1/,
    );
    expect(first.at(-1)?.text).toMatch(/Passing score: 80 %/);
    // Second call: the same conversation plus the answer and the problems found.
    const second = client.calls[1]?.messages ?? [];
    expect(second).toHaveLength(3);
    expect(JSON.stringify(second[2])).toMatch(/source-ref.*h-invented/);

    const yaml = readFileSync(join(dir, "storyboard.yaml"), "utf8");
    expect(yaml).toMatch(/^# Storyboard generated by Claude \(claude-opus-5-5/);
    expect(existsSync(join(dir, "review/storyboard.html"))).toBe(true);
    const log = JSON.parse(readFileSync(join(dir, GENERATION_LOG), "utf8"));
    expect(log).toMatchObject({ step: "storyboard", rounds: 2, errors: 0 });
  });

  it("writes nothing when no answer is a storyboard", async () => {
    const dir = demo();
    await expect(
      generateStoryboard(dir, { client: fake(["not json", "{}", "[]"]) }),
    ).rejects.toThrow(GenerationError);
    expect(existsSync(join(dir, "storyboard.yaml"))).toBe(false);
  });

  it("refuses to work on sources changed since they were read", async () => {
    const dir = demo();
    cpSync(join(DEMO, "README.md"), join(dir, "sources", "extra.md"));
    await expect(generateStoryboard(dir, { client: fake([]) })).rejects.toThrow(
      /extra\.md/,
    );
  });
});

describe("estimateStoryboard", () => {
  it("prices one short answer to three long ones from the exact input size", async () => {
    const e = await estimateStoryboard(demo(), { client: fake([]) });
    expect(e).toMatchObject({ model: "claude-opus-5-5", inputTokens: 20_000 });
    expect(e.lowUsd).toBeCloseTo((20_000 * 4 + 8_000 * 20) / 1e6);
    expect(e.highUsd).toBeGreaterThan(1);
  });
});
